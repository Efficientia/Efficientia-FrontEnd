import { useState, type FormEvent } from 'react';
import { Link, useNavigate } from 'react-router-dom';
import { useAuth } from '../../hooks/useAuth';
import { empresaService } from '../../services/empresaService';
import { authService } from '../../services/authService';
import { normalizeApiError, type ApiRequestError } from '../../services/api';
import type {
  CriarPrimeiroAdminRequest,
  SignupRequest,
  TipoUsuario,
} from '../../types/auth';
import type { CriarEmpresaRequest } from '../../types/empresa';
import {
  formatCnpj,
  formatCpf,
  formatTelefone,
  isAtLeast18YearsOld,
} from '../../utils/validators';
import caminhaoImg from '../../assets/caminhao-cadastro.png';
import './Cadastro.css';

type CadastroMode = 'empresa' | 'primeiro-admin' | 'operacional';

export function Cadastro() {
  const navigate = useNavigate();
  const { cadastrarPrimeiroAdmin } = useAuth();

  const [mode, setMode] = useState<CadastroMode>('empresa');

  // Estado Modalidade 1: Nova Empresa (POST /api/v1/empresas)
  const [empNome, setEmpNome] = useState('');
  const [empRazaoSocial, setEmpRazaoSocial] = useState('');
  const [empCnpj, setEmpCnpj] = useState('');
  const [empEmail, setEmpEmail] = useState('');
  const [empSenha, setEmpSenha] = useState('');

  // Estado Modalidade 2: Primeiro Administrador (POST /api/v1/auth/adm/primeiro-acesso)
  const [admCodigoEmpresa, setAdmCodigoEmpresa] = useState('');
  const [isCodigoAutoGenerated, setIsCodigoAutoGenerated] = useState(false);
  const [admNome, setAdmNome] = useState('');
  const [admEmail, setAdmEmail] = useState('');
  const [admSenha, setAdmSenha] = useState('');
  const [admCnpj, setAdmCnpj] = useState('');

  // Estado Modalidade 3: Usuário Operacional (POST /api/v1/auth/signup)
  const [opTipo, setOpTipo] = useState<TipoUsuario>('motorista');
  const [opNome, setOpNome] = useState('');
  const [opCpf, setOpCpf] = useState('');
  const [opCodigoEmpresa, setOpCodigoEmpresa] = useState('');
  const [opDataNascimento, setOpDataNascimento] = useState('');
  const [opTelefone, setOpTelefone] = useState('');
  const [opEmail, setOpEmail] = useState('');
  const [opSenha, setOpSenha] = useState('');

  const [touched, setTouched] = useState<Record<string, boolean>>({});
  const [error, setError] = useState<ApiRequestError | null>(null);
  const [successNotice, setSuccessNotice] = useState('');
  const [isSubmitting, setIsSubmitting] = useState(false);

  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

  // Validações Empresa
  const cleanEmpCnpj = empCnpj.replace(/\D/g, '');
  const isEmpNomeValid = empNome.trim().length >= 2;
  const isEmpCnpjValid = cleanEmpCnpj.length === 14;
  const isEmpEmailValid = emailRegex.test(empEmail.trim());
  const isEmpresaFormValid = isEmpNomeValid && isEmpCnpjValid && isEmpEmailValid;

  // Validações Primeiro Admin
  const isAdmCodigoValid = admCodigoEmpresa.trim().length >= 2;
  const isAdmNomeValid = admNome.trim().length >= 2;
  const isAdmEmailValid = emailRegex.test(admEmail.trim());
  const isAdmSenhaValid = admSenha.trim().length >= 6;
  const isPrimeiroAdminFormValid =
    isAdmCodigoValid && isAdmNomeValid && isAdmEmailValid && isAdmSenhaValid;

  // Validações Operacional
  const cleanOpCpf = opCpf.replace(/\D/g, '');
  const isOpNomeValid = opNome.trim().length >= 2;
  const isOpCpfValid = cleanOpCpf.length === 11;
  const isOpCodigoValid = opCodigoEmpresa.trim().length >= 2;
  const isOpEmailValid = emailRegex.test(opEmail.trim());
  const isOpTelefoneValid = opTelefone.replace(/\D/g, '').length >= 10;
  const isOpSenhaValid = opSenha.trim().length >= 6;
  const isOpAgeValid = isAtLeast18YearsOld(opDataNascimento);
  const isOperacionalFormValid =
    isOpNomeValid &&
    isOpCpfValid &&
    isOpCodigoValid &&
    isOpEmailValid &&
    isOpTelefoneValid &&
    isOpSenhaValid &&
    isOpAgeValid;

  const isFormValid =
    mode === 'empresa'
      ? isEmpresaFormValid
      : mode === 'primeiro-admin'
      ? isPrimeiroAdminFormValid
      : isOperacionalFormValid;

  async function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setError(null);
    setSuccessNotice('');

    if (mode === 'empresa') {
      setTouched({ empNome: true, empCnpj: true, empEmail: true });
      if (!isEmpresaFormValid) return;

      setIsSubmitting(true);
      try {
        const payload: CriarEmpresaRequest = {
          nomeEmpresa: empNome.trim(),
          razaoSocial: empRazaoSocial.trim() || empNome.trim(),
          cnpj: cleanEmpCnpj,
          emailCorporativo: empEmail.trim().toLowerCase(),
          ...(empSenha.trim() ? { senha: empSenha } : {}),
        };

        const empresaCriada = await empresaService.cadastrarEmpresa(payload);
        const generatedCode =
          empresaCriada.codigoEmpresa || empresaCriada.codigo || empresaCriada.codigoInterno || '';

        setSuccessNotice(
          `Empresa registrada com sucesso! Código gerado: ${generatedCode}. Prossiga com o cadastro do 1º Administrador.`
        );

        // Preenche automaticamente o código e o CNPJ e avança para a aba de Primeiro Administrador
        setAdmCodigoEmpresa(generatedCode);
        setIsCodigoAutoGenerated(true);
        setAdmCnpj(formatCnpj(cleanEmpCnpj));
        setAdmEmail(empEmail.trim().toLowerCase());
        setMode('primeiro-admin');
      } catch (requestError) {
        setError(normalizeApiError(requestError));
      } finally {
        setIsSubmitting(false);
      }
    } else if (mode === 'primeiro-admin') {
      setTouched({ admCodigoEmpresa: true, admNome: true, admEmail: true, admSenha: true });
      if (!isPrimeiroAdminFormValid) return;

      setIsSubmitting(true);
      try {
        const cleanCnpj = admCnpj.replace(/\D/g, '');
        const payload: CriarPrimeiroAdminRequest = {
          codigoEmpresa: admCodigoEmpresa.trim().toUpperCase(),
          nome: admNome.trim(),
          email: admEmail.trim().toLowerCase(),
          senha: admSenha,
          ...(cleanCnpj.length === 14 ? { cnpj: cleanCnpj } : {}),
        };

        await cadastrarPrimeiroAdmin(payload);
        setSuccessNotice('Primeiro Administrador criado com sucesso! Redirecionando para o painel...');
        setTimeout(() => {
          navigate('/dashboard', { replace: true });
        }, 1600);
      } catch (requestError) {
        setError(normalizeApiError(requestError));
      } finally {
        setIsSubmitting(false);
      }
    } else {
      setTouched({
        opNome: true,
        opCpf: true,
        opCodigoEmpresa: true,
        opTelefone: true,
        opEmail: true,
        opSenha: true,
        opDataNascimento: true,
      });
      if (!isOperacionalFormValid) return;

      setIsSubmitting(true);
      try {
        const payload: SignupRequest = {
          tipo: opTipo,
          nome: opNome.trim(),
          cpf: cleanOpCpf,
          codigoInterno: opCodigoEmpresa.trim().toUpperCase(),
          email: opEmail.trim().toLowerCase(),
          telefone: opTelefone.replace(/\D/g, ''),
          senha: opSenha,
          ...(opDataNascimento ? { dataNascimento: opDataNascimento } : {}),
        };

        await authService.signupUsuario(payload);
        setSuccessNotice('Usuário operacional cadastrado com sucesso! Redirecionando para o login...');
        setTimeout(() => {
          navigate('/login', { replace: true });
        }, 1600);
      } catch (requestError) {
        setError(normalizeApiError(requestError));
      } finally {
        setIsSubmitting(false);
      }
    }
  }

  return (
    <main id="main-content" className="cadastro-container" aria-labelledby="cadastro-title" tabIndex={-1}>
      <section className="cadastro-form-section">
        <div className="cadastro-content">
          <h1 id="cadastro-title" className="cadastro-title">Cadastro</h1>

          {/* Seletores de Perfil/Modo segundo API-Map */}
          <div className="auth-mode-selector" role="tablist" aria-label="Selecione o tipo de cadastro">
            <button
              type="button"
              role="tab"
              aria-selected={mode === 'empresa'}
              className={`auth-mode-btn ${mode === 'empresa' ? 'active' : ''}`}
              onClick={() => {
                setMode('empresa');
                setError(null);
                setSuccessNotice('');
              }}
            >
              Nova Empresa
            </button>
            <button
              type="button"
              role="tab"
              aria-selected={mode === 'primeiro-admin'}
              className={`auth-mode-btn ${mode === 'primeiro-admin' ? 'active' : ''}`}
              onClick={() => {
                setMode('primeiro-admin');
                setError(null);
                setSuccessNotice('');
              }}
            >
              1º Administrador
            </button>
            <button
              type="button"
              role="tab"
              aria-selected={mode === 'operacional'}
              className={`auth-mode-btn ${mode === 'operacional' ? 'active' : ''}`}
              onClick={() => {
                setMode('operacional');
                setError(null);
                setSuccessNotice('');
              }}
            >
              Usuário Operacional
            </button>
          </div>

          <p className="form-legend">
            <span className="field-required">*</span> Campos obrigatórios
          </p>

          <form className="cadastro-form" onSubmit={handleSubmit} noValidate>
            {mode === 'empresa' && (
              /* Formulário Nova Empresa (POST /api/v1/empresas) */
              <>
                {/* Nota do sistema: Código da empresa é gerado automaticamente e NÃO é input */}
                <div className="system-auto-notice" role="note">
                  <span>
                    ℹ️ <strong>Código da Empresa:</strong> Gerado automaticamente pelo sistema após este cadastro. Não é necessário digitá-lo aqui.
                  </span>
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-emp-nome" className="field-label">
                    <span>Nome Fantasia <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-emp-nome"
                    name="empNome"
                    type="text"
                    placeholder="Nome Fantasia"
                    autoComplete="organization"
                    required
                    value={empNome}
                    onBlur={() => setTouched((prev) => ({ ...prev, empNome: true }))}
                    onChange={(e) => {
                      setEmpNome(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.empNome && !isEmpNomeValid ? 'has-error' : ''}`}
                    aria-invalid={touched.empNome && !isEmpNomeValid}
                  />
                  {touched.empNome && !isEmpNomeValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe o nome da empresa.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-emp-razao" className="field-label">
                    <span>Razão Social</span>
                    <span className="field-optional">Opcional</span>
                  </label>
                  <input
                    id="cad-emp-razao"
                    name="empRazaoSocial"
                    type="text"
                    placeholder="Razão Social"
                    autoComplete="organization"
                    value={empRazaoSocial}
                    onChange={(e) => setEmpRazaoSocial(e.target.value)}
                    className="cadastro-input"
                  />
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-emp-cnpj" className="field-label">
                    <span>CNPJ <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-emp-cnpj"
                    name="empCnpj"
                    type="text"
                    placeholder="CNPJ"
                    autoComplete="organization"
                    required
                    value={empCnpj}
                    onBlur={() => setTouched((prev) => ({ ...prev, empCnpj: true }))}
                    onChange={(e) => {
                      setEmpCnpj(formatCnpj(e.target.value));
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.empCnpj && !isEmpCnpjValid ? 'has-error' : ''}`}
                    aria-invalid={touched.empCnpj && !isEmpCnpjValid}
                  />
                  {touched.empCnpj && !isEmpCnpjValid && (
                    <span className="cadastro-field-error" role="alert">
                      O CNPJ deve conter exatamente 14 dígitos.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-emp-email" className="field-label">
                    <span>E-mail Corporativo <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-emp-email"
                    name="empEmail"
                    type="email"
                    placeholder="E-mail Corporativo"
                    autoComplete="email"
                    required
                    value={empEmail}
                    onBlur={() => setTouched((prev) => ({ ...prev, empEmail: true }))}
                    onChange={(e) => {
                      setEmpEmail(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.empEmail && !isEmpEmailValid ? 'has-error' : ''}`}
                    aria-invalid={touched.empEmail && !isEmpEmailValid}
                  />
                  {touched.empEmail && !isEmpEmailValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe um e-mail corporativo válido.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-emp-senha" className="field-label">
                    <span>Senha Corporativa</span>
                    <span className="field-optional">Opcional</span>
                  </label>
                  <input
                    id="cad-emp-senha"
                    name="empSenha"
                    type="password"
                    placeholder="Senha Corporativa"
                    autoComplete="new-password"
                    value={empSenha}
                    onChange={(e) => setEmpSenha(e.target.value)}
                    className="cadastro-input"
                  />
                </div>
              </>
            )}

            {mode === 'primeiro-admin' && (
              /* Formulário Primeiro Administrador (POST /api/v1/auth/adm/primeiro-acesso) */
              <>
                <div className="cadastro-input-group">
                  <label htmlFor="cad-adm-codigo" className="field-label">
                    <span>
                      Código da Empresa <span className="field-required">*</span>
                      {isCodigoAutoGenerated && (
                        <span className="system-auto-badge">Preenchido pelo sistema</span>
                      )}
                    </span>
                  </label>
                  <input
                    id="cad-adm-codigo"
                    name="admCodigoEmpresa"
                    type="text"
                    placeholder="Código da Empresa"
                    autoComplete="organization"
                    required
                    value={admCodigoEmpresa}
                    onBlur={() => setTouched((prev) => ({ ...prev, admCodigoEmpresa: true }))}
                    onChange={(e) => {
                      setAdmCodigoEmpresa(e.target.value.toUpperCase());
                      setIsCodigoAutoGenerated(false);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${
                      touched.admCodigoEmpresa && !isAdmCodigoValid ? 'has-error' : ''
                    }`}
                    aria-invalid={touched.admCodigoEmpresa && !isAdmCodigoValid}
                  />
                  {touched.admCodigoEmpresa && !isAdmCodigoValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe o código da empresa previamente cadastrada.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-adm-nome" className="field-label">
                    <span>Nome Completo do Gestor <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-adm-nome"
                    name="admNome"
                    type="text"
                    placeholder="Nome Completo do Gestor"
                    autoComplete="name"
                    required
                    value={admNome}
                    onBlur={() => setTouched((prev) => ({ ...prev, admNome: true }))}
                    onChange={(e) => {
                      setAdmNome(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.admNome && !isAdmNomeValid ? 'has-error' : ''}`}
                    aria-invalid={touched.admNome && !isAdmNomeValid}
                  />
                  {touched.admNome && !isAdmNomeValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe seu nome completo.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-adm-email" className="field-label">
                    <span>E-mail do Administrador <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-adm-email"
                    name="admEmail"
                    type="email"
                    placeholder="E-mail do Administrador"
                    autoComplete="email"
                    required
                    value={admEmail}
                    onBlur={() => setTouched((prev) => ({ ...prev, admEmail: true }))}
                    onChange={(e) => {
                      setAdmEmail(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.admEmail && !isAdmEmailValid ? 'has-error' : ''}`}
                    aria-invalid={touched.admEmail && !isAdmEmailValid}
                  />
                  {touched.admEmail && !isAdmEmailValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe um e-mail válido.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-adm-senha" className="field-label">
                    <span>Senha <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-adm-senha"
                    name="admSenha"
                    type="password"
                    placeholder="Senha"
                    autoComplete="new-password"
                    required
                    value={admSenha}
                    onBlur={() => setTouched((prev) => ({ ...prev, admSenha: true }))}
                    onChange={(e) => {
                      setAdmSenha(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.admSenha && !isAdmSenhaValid ? 'has-error' : ''}`}
                    aria-invalid={touched.admSenha && !isAdmSenhaValid}
                  />
                  {touched.admSenha && !isAdmSenhaValid && (
                    <span className="cadastro-field-error" role="alert">
                      A senha deve conter no mínimo 6 caracteres.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-adm-cnpj" className="field-label">
                    <span>CNPJ da Empresa</span>
                    <span className="field-optional">Opcional</span>
                  </label>
                  <input
                    id="cad-adm-cnpj"
                    name="admCnpj"
                    type="text"
                    placeholder="CNPJ da Empresa"
                    autoComplete="organization"
                    value={admCnpj}
                    onChange={(e) => setAdmCnpj(formatCnpj(e.target.value))}
                    className="cadastro-input"
                  />
                </div>
              </>
            )}

            {mode === 'operacional' && (
              /* Formulário Usuário Operacional (POST /api/v1/auth/signup) */
              <>
                <div className="cadastro-input-group">
                  <label htmlFor="cad-op-tipo" className="field-label">
                    <span>Tipo de Usuário <span className="field-required">*</span></span>
                  </label>
                  <select
                    id="cad-op-tipo"
                    name="opTipo"
                    value={opTipo}
                    onChange={(e) => setOpTipo(e.target.value as TipoUsuario)}
                    className="cadastro-input cadastro-select"
                  >
                    <option value="motorista">Motorista</option>
                    <option value="analista">Analista</option>
                    <option value="manobrista">Manobrista</option>
                    <option value="curraleiro">Curraleiro</option>
                    <option value="pecuarista">Pecuarista</option>
                  </select>
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-op-nome" className="field-label">
                    <span>Nome Completo <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-op-nome"
                    name="opNome"
                    type="text"
                    placeholder="Nome Completo"
                    autoComplete="name"
                    required
                    value={opNome}
                    onBlur={() => setTouched((prev) => ({ ...prev, opNome: true }))}
                    onChange={(e) => {
                      setOpNome(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.opNome && !isOpNomeValid ? 'has-error' : ''}`}
                    aria-invalid={touched.opNome && !isOpNomeValid}
                  />
                  {touched.opNome && !isOpNomeValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe seu nome completo.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-op-cpf" className="field-label">
                    <span>CPF <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-op-cpf"
                    name="opCpf"
                    type="text"
                    placeholder="CPF"
                    autoComplete="username"
                    required
                    value={opCpf}
                    onBlur={() => setTouched((prev) => ({ ...prev, opCpf: true }))}
                    onChange={(e) => {
                      setOpCpf(formatCpf(e.target.value));
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.opCpf && !isOpCpfValid ? 'has-error' : ''}`}
                    aria-invalid={touched.opCpf && !isOpCpfValid}
                  />
                  {touched.opCpf && !isOpCpfValid && (
                    <span className="cadastro-field-error" role="alert">
                      O CPF deve conter exatamente 11 dígitos.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-op-codigo" className="field-label">
                    <span>Código da Empresa <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-op-codigo"
                    name="opCodigoEmpresa"
                    type="text"
                    placeholder="Código da Empresa"
                    autoComplete="organization"
                    required
                    value={opCodigoEmpresa}
                    onBlur={() => setTouched((prev) => ({ ...prev, opCodigoEmpresa: true }))}
                    onChange={(e) => {
                      setOpCodigoEmpresa(e.target.value.toUpperCase());
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${
                      touched.opCodigoEmpresa && !isOpCodigoValid ? 'has-error' : ''
                    }`}
                    aria-invalid={touched.opCodigoEmpresa && !isOpCodigoValid}
                  />
                  {touched.opCodigoEmpresa && !isOpCodigoValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe o código da empresa.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-op-nasc" className="field-label">
                    <span>Data de Nascimento</span>
                    <span className="field-optional">Opcional</span>
                  </label>
                  <input
                    id="cad-op-nasc"
                    name="opDataNascimento"
                    type="date"
                    placeholder="Data de Nascimento"
                    value={opDataNascimento}
                    onBlur={() => setTouched((prev) => ({ ...prev, opDataNascimento: true }))}
                    onChange={(e) => {
                      setOpDataNascimento(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${
                      touched.opDataNascimento && !isOpAgeValid ? 'has-error' : ''
                    }`}
                    aria-invalid={touched.opDataNascimento && !isOpAgeValid}
                  />
                  {touched.opDataNascimento && !isOpAgeValid && (
                    <span className="cadastro-field-error" role="alert">
                      O usuário deve possuir no mínimo 18 anos completos.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-op-tel" className="field-label">
                    <span>Telefone <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-op-tel"
                    name="opTelefone"
                    type="tel"
                    placeholder="Telefone com DDD"
                    autoComplete="tel"
                    required
                    value={opTelefone}
                    onBlur={() => setTouched((prev) => ({ ...prev, opTelefone: true }))}
                    onChange={(e) => {
                      setOpTelefone(formatTelefone(e.target.value));
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.opTelefone && !isOpTelefoneValid ? 'has-error' : ''}`}
                    aria-invalid={touched.opTelefone && !isOpTelefoneValid}
                  />
                  {touched.opTelefone && !isOpTelefoneValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe um número de telefone válido com DDD.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-op-email" className="field-label">
                    <span>E-mail <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-op-email"
                    name="opEmail"
                    type="email"
                    placeholder="E-mail"
                    autoComplete="email"
                    required
                    value={opEmail}
                    onBlur={() => setTouched((prev) => ({ ...prev, opEmail: true }))}
                    onChange={(e) => {
                      setOpEmail(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.opEmail && !isOpEmailValid ? 'has-error' : ''}`}
                    aria-invalid={touched.opEmail && !isOpEmailValid}
                  />
                  {touched.opEmail && !isOpEmailValid && (
                    <span className="cadastro-field-error" role="alert">
                      Informe um e-mail válido.
                    </span>
                  )}
                </div>

                <div className="cadastro-input-group">
                  <label htmlFor="cad-op-senha" className="field-label">
                    <span>Senha <span className="field-required">*</span></span>
                  </label>
                  <input
                    id="cad-op-senha"
                    name="opSenha"
                    type="password"
                    placeholder="Senha"
                    autoComplete="new-password"
                    required
                    value={opSenha}
                    onBlur={() => setTouched((prev) => ({ ...prev, opSenha: true }))}
                    onChange={(e) => {
                      setOpSenha(e.target.value);
                      if (error) setError(null);
                    }}
                    className={`cadastro-input ${touched.opSenha && !isOpSenhaValid ? 'has-error' : ''}`}
                    aria-invalid={touched.opSenha && !isOpSenhaValid}
                  />
                  {touched.opSenha && !isOpSenhaValid && (
                    <span className="cadastro-field-error" role="alert">
                      A senha deve conter no mínimo 6 caracteres.
                    </span>
                  )}
                </div>
              </>
            )}

            {error && (
              <div className="cadastro-feedback cadastro-feedback-error" role="alert">
                <p>{error.message}</p>
                {Object.entries(error.fieldErrors).length > 0 && (
                  <ul>
                    {Object.entries(error.fieldErrors).map(([field, msg]) => (
                      <li key={field}>
                        {field}: {msg}
                      </li>
                    ))}
                  </ul>
                )}
              </div>
            )}

            {successNotice && (
              <div className="cadastro-feedback cadastro-feedback-success" role="status">
                <p>{successNotice}</p>
              </div>
            )}

            <div className="cadastro-switch-box">
              <p className="cadastro-switch-text">
                Já possui uma conta?{' '}
                <Link to="/login" className="cadastro-switch-link">
                  Entre
                </Link>
              </p>
            </div>

            <button
              type="submit"
              className="cadastro-submit-btn"
              disabled={isSubmitting || !isFormValid}
              title={
                !isFormValid
                  ? mode === 'empresa'
                    ? 'Preencha os campos obrigatórios (*)'
                    : mode === 'primeiro-admin'
                    ? 'Preencha os campos obrigatórios (*)'
                    : 'Preencha todos os campos obrigatórios (*)'
                  : undefined
              }
            >
              {isSubmitting
                ? 'Cadastrando...'
                : mode === 'empresa'
                ? 'Cadastrar Empresa'
                : mode === 'primeiro-admin'
                ? 'Cadastrar Administrador'
                : 'Cadastrar Usuário'}
            </button>
          </form>
        </div>
      </section>

      <section className="cadastro-hero-section" aria-label="Apresentação Efficientia">
        <div className="cadastro-hero-overlay" />
        <img
          src={caminhaoImg}
          alt="Caminhão boiadeiro com a marca Efficientia - Gestão que move o campo"
          className="cadastro-hero-img"
        />
      </section>
    </main>
  );
}

export default Cadastro;
